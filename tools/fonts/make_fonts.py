#!/usr/bin/env python3
"""Generates firmware/controller/fonts.h: anti-aliased (2 bits/pixel, 4 levels) proportional bitmap fonts
for scr_gfx.cpp ftxt(). Chars 32..126, and slot 127 holds the degree sign (code 0xF8 in strings, cp437 style).
Run from the repo root:  python3 tools/fonts/make_fonts.py   (then copy fonts.h into tests/11_ui_dev)
Fonts: DejaVu Sans / Sans Mono (Bitstream Vera licence) and GNU FreeSans (GPL with font exception)."""
import os, sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DJ = '/usr/share/fonts/truetype/dejavu/'
FF = '/usr/share/fonts/truetype/freefont/'
ALL = [chr(c) for c in range(32, 127)] + ['°']
NUM = list(' +-.0123456789') + ['°']
FONTS = [  # name, ttf, px size, charset
    ('F_LABEL', DJ + 'DejaVuSans.ttf', 10, ALL),
    ('F_VALUE', DJ + 'DejaVuSans-Bold.ttf', 15, ALL),
    ('F_BIG', FF + 'FreeSansBold.ttf', 33, NUM),            # Mode 1 big temperatures
    ('F_SPORT', FF + 'FreeSansBoldOblique.ttf', 34, NUM),   # Mode 2 big temperatures (slanted)
    ('F_MONO', DJ + 'DejaVuSansMono.ttf', 11, ALL),         # Mode 3, 7 px per char
]

def build(name, path, size, chars):
    font = ImageFont.truetype(path, size)
    asc, desc = font.getmetrics()
    # vertical crop: union of the ink of every glyph (keeps all fonts tight)
    top, bot = 10 ** 6, -1
    for ch in chars:
        bb = font.getbbox(ch, anchor='ls')
        if bb[2] > bb[0]:
            top, bot = min(top, bb[1]), max(bot, bb[3])
    h = bot - top
    widths, offs, bits, previews = [], [], [], {}
    for code in range(32, 128):
        ch = '°' if code == 127 else chr(code)
        if ch not in chars:
            widths.append(0); offs.append(len(bits)); continue
        # cell = advance, widened to hold ink that overhangs it (oblique digits lean 2-5 px past their
        # advance; cut at the advance, the next glyph's cell would paint over it and the last one is clipped)
        bb = font.getbbox(ch, anchor='ls')
        lpad = max(0, -bb[0])
        adv = max(1, round(font.getlength(ch)), bb[2]) + lpad
        im = Image.new('L', (adv, h), 0)
        ImageDraw.Draw(im).text((lpad, -top), ch, font=font, fill=255, anchor='ls')
        px = im.load()
        lv = [min(3, (px[x, y] * 4) // 256) for y in range(h) for x in range(adv)]
        offs.append(len(bits))
        for i in range(0, len(lv), 4):
            b = 0
            for k, v in enumerate(lv[i:i + 4]):
                b |= v << (2 * k)
            bits.append(b)
        widths.append(adv)
        previews[ch] = (adv, lv)
    return h, widths, offs, bits

def main():
    out = ['#pragma once',
           '// GENERATED by tools/fonts/make_fonts.py - do not edit.',
           '// 2-bit anti-aliased proportional fonts, chars 32..126, slot 127 = degree sign (write it as \\xF8).',
           '#include <Arduino.h>', '',
           'struct Font {', '  uint8_t h;                // pixel rows (tight ink box of the charset)',
           '  const uint8_t *w;         // advance width per char 32..127, PROGMEM (0 = not in this font)',
           '  const uint16_t *off;      // byte offset of each glyph in bits, PROGMEM',
           '  const uint8_t *bits;      // row-major, 4 pixels per byte, low bits first, PROGMEM',
           '};', '']
    total = 0
    for name, path, size, chars in FONTS:
        h, w, o, b = build(name, path, size, chars)
        total += len(b) + len(w) + 2 * len(o)
        out.append(f'static const uint8_t {name}_W[96] PROGMEM = {{' + ','.join(map(str, w)) + '};')
        out.append(f'static const uint16_t {name}_OFF[96] PROGMEM = {{' + ','.join(map(str, o)) + '};')
        out.append(f'static const uint8_t {name}_BITS[] PROGMEM = {{')
        for i in range(0, len(b), 32):
            out.append('  ' + ','.join(map(str, b[i:i + 32])) + ',')
        out.append('};')
        out.append(f'static const Font {name} = {{{h}, {name}_W, {name}_OFF, {name}_BITS}};')
        out.append('')
        print(f'{name}: {os.path.basename(path)} {size}px -> {h} rows, {len(b)} B')
    p = os.path.join(ROOT, 'firmware/controller/fonts.h')
    open(p, 'w').write('\n'.join(out))
    print(f'wrote {p} ({total} B flash)')

if __name__ == '__main__':
    main()
