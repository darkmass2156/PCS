#!/usr/bin/env python3
"""Builds stub/font5x7.h: a 5x7 look-alike of the Adafruit GFX built-in font (host preview only;
the firmware uses the real one). ASCII 32..126 plus cp437 248 (degree)."""
import os
from PIL import Image, ImageDraw, ImageFont
here = os.path.dirname(os.path.abspath(__file__))
font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf', 9)
cols = {}
for code in list(range(32, 127)) + [248]:
    ch = '°' if code == 248 else chr(code)
    im = Image.new('L', (5, 8), 0)
    d = ImageDraw.Draw(im)
    d.text((0, -1), ch, font=font, fill=255)
    px = im.load()
    cols[code] = [sum((1 << y) for y in range(8) if px[x, y] > 110) for x in range(5)]
out = ['#pragma once', '// GENERATED by make_font.py - 5x7 look-alike of the GFX font, host preview only.',
       'static const unsigned char FONT5X7[256][5] = {']
for c in range(256):
    out.append('  {' + ','.join(str(v) for v in cols.get(c, [0] * 5)) + '},')
out.append('};')
open(os.path.join(here, 'stub/font5x7.h'), 'w').write('\n'.join(out) + '\n')
