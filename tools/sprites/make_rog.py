#!/usr/bin/env python3
"""Converts docs/display/rog_logo_280x240.png (white logo on black, Vlad's 280x240 artwork) into
firmware/controller/rog_logo.h: the logo's bounding box as 1-bit run lengths.

Encoding: per row, run lengths alternate background / logo, starting with background; each byte is one
run (0..255; a 0 run lets a longer run continue in the same colour). A row ends when it has ROG_W pixels.
Run from the repo root:  python3 tools/sprites/make_rog.py   (then copy rog_logo.h into tests/11_ui_dev)
"""
import os
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
im = Image.open(os.path.join(root, "docs/display/rog_logo_280x240.png")).convert("L").point(lambda v: 255 if v > 128 else 0)
x0, y0, x1, y1 = im.getbbox()
w, h = x1 - x0, y1 - y0
px = im.load()
data = []
for y in range(y0, y1):
    runs = []                      # merged (colour, length) for this row
    for x in range(x0, x1):
        v = 1 if px[x, y] else 0
        if runs and runs[-1][0] == v:
            runs[-1][1] += 1
        else:
            runs.append([v, 1])
    if runs[0][0] == 1:
        runs.insert(0, [0, 0])     # rows always start with a background run
    for i, (c, n) in enumerate(runs):
        while n > 255:             # split long runs: 255, then an empty run of the other colour
            data += [255, 0]
            n -= 255
        data.append(n)

# round-trip check with the same algorithm the firmware uses
pos = 0
for y in range(y0, y1):
    x, col = 0, 0
    while x < w:
        n = data[pos]; pos += 1
        for k in range(n):
            assert (1 if px[x0 + x + k, y] else 0) == col, (y, x)
        x += n; col ^= 1
    assert x == w
assert pos == len(data)
lines = [
    "#pragma once",
    "// GENERATED by tools/sprites/make_rog.py from docs/display/rog_logo_280x240.png — do not edit.",
    "// 1-bit run lengths of the logo's bounding box: per row, runs alternate background/logo starting",
    "// with background (a 0 run lets a run longer than 255 continue). Decode until the row has ROG_W pixels.",
    "#include <Arduino.h>",
    "",
    f"#define ROG_X0 {x0}   // position inside the 280x240 artwork",
    f"#define ROG_Y0 {y0}",
    f"#define ROG_W {w}",
    f"#define ROG_H {h}",
    f"static const uint16_t ROG_LEN = {len(data)};",
    "static const uint8_t ROG_RLE[] PROGMEM = {",
]
for i in range(0, len(data), 24):
    lines.append("  " + ", ".join(str(v) for v in data[i:i + 24]) + ",")
lines += ["};", ""]
out = os.path.join(root, "firmware/controller/rog_logo.h")
open(out, "w").write("\n".join(lines))
print(f"wrote {out}: {w}x{h} at {x0},{y0}, {len(data)} bytes")
